import { User } from '@prisma/client'; // Adjust import if User type is different
import { Role } from '@prisma/client'; // Assuming Role enum is generated by Prisma

export { Role }; // Re-export Role for convenience

/**
 * Checks if a user has at least one of the specified roles.
 * @param user The user object (must include a 'role' property).
 * @param roles An array of roles to check against.
 * @returns True if the user has one of the specified roles, false otherwise.
 */
export const hasRole = (user: Pick<User, 'role'> | null | undefined, roles: Role[]): boolean => {
  if (!user || !user.role) {
    return false;
  }
  return roles.includes(user.role as Role); // Added type assertion for user.role
};

/**
 * Checks if a user is an Admin.
 * @param user The user object.
 * @returns True if the user is an Admin, false otherwise.
 */
export const isAdmin = (user: Pick<User, 'role'> | null | undefined): boolean => {
  return hasRole(user, [Role.ADMIN]);
};

/**
 * Checks if a user is a Marketer.
 * @param user The user object.
 * @returns True if the user is a Marketer, false otherwise.
 */
export const isMarketer = (user: Pick<User, 'role'> | null | undefined): boolean => {
  return hasRole(user, [Role.MARKETER]);
};

/**
 * Checks if a user is a Designer.
 * @param user The user object.
 * @returns True if the user is a Designer, false otherwise.
 */
export const isDesigner = (user: Pick<User, 'role'> | null | undefined): boolean => {
  return hasRole(user, [Role.DESIGNER]);
};

